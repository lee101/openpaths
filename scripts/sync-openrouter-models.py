#!/usr/bin/env python3
"""Sync OpenRouter models into config.yaml and src/data/models.ts.

Pulls https://openrouter.ai/api/v1/models and rewrites the generated
openrouter-sync blocks: every tool-capable :free model (ladder ordered by
scripts/openrouter-sync.json free_rank, openrouter/free last), the
openpaths/free entry that walks that ladder, and the paid ids listed in
openrouter-sync.json. Paid prices are OpenRouter's advertised rate plus the
OpenRouter fee, rounded up. Hand-written entries outside the blocks win:
a model already configured there is referenced, never duplicated.

  python3 scripts/sync-openrouter-models.py            # write
  python3 scripts/sync-openrouter-models.py --check    # exit 1 on drift
  python3 scripts/sync-openrouter-models.py --add minimax/minimax-m3
"""
import argparse
import datetime
import json
import re
import sys
import urllib.request
from decimal import ROUND_CEILING, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "config.yaml"
SITE = ROOT / "src" / "data" / "models.ts"
CAPS = ROOT / "src" / "data" / "capabilities.ts"
SETTINGS = Path(__file__).with_name("openrouter-sync.json")
CATALOG_URL = "https://openrouter.ai/api/v1/models"
ROUTER = "openrouter/free"
FREE_ID = "openpaths/free"

Y_BEGIN = "  # --- BEGIN openrouter-sync: generated by scripts/sync-openrouter-models.py; edit openrouter-sync.json, not this block ---"
Y_END = "  # --- END openrouter-sync ---"
T_BEGIN = "  // --- BEGIN openrouter-sync: generated by scripts/sync-openrouter-models.py ---"
T_END = "  // --- END openrouter-sync ---"
Y_ANCHOR = "  # --- Nous Research ---"
T_ANCHOR = "\n];\n\nexport function isPromotionActive"


def split_block(text, begin, end):
    if begin not in text:
        return text, None, ""
    head, rest = text.split(begin, 1)
    body, tail = rest.split(end, 1)
    return head, body, tail


def manual_models(yaml_text):
    """id/aliases/provider/provider_model_id of hand-written config entries."""
    models, cur = [], None
    in_models = False
    for line in yaml_text.splitlines():
        if line.startswith("models:"):
            in_models = True
            continue
        if in_models and line and not line.startswith(" "):
            in_models = False
        if not in_models:
            continue
        if m := re.match(r'  - id: "?([^"\s]+)"?', line):
            cur = {"id": m[1], "aliases": [], "provider": "", "pmid": ""}
            models.append(cur)
        elif cur and (m := re.match(r"    aliases: \[(.*)\]", line)):
            cur["aliases"] = [a.strip().strip('"\'') for a in m[1].split(",") if a.strip()]
        elif cur and (m := re.match(r'    provider: "?([^"\s]+)"?', line)):
            cur["provider"] = m[1]
        elif cur and (m := re.match(r'    provider_model_id: "?([^"]+?)"?\s*$', line)):
            cur["pmid"] = m[1]
    return models


def per_million(per_token, fee):
    v = Decimal(str(per_token or 0)) * 1_000_000 * (1 + Decimal(str(fee)))
    return float(v.quantize(Decimal("0.0001"), rounding=ROUND_CEILING))


def raw_per_million(per_token):
    return float((Decimal(str(per_token or 0)) * 1_000_000).normalize())


def fmt(x):
    return ("%.4f" % x).rstrip("0").rstrip(".") if x else "0"


def ctx_label(n):
    return f"{n // 1_000_000}M" if n >= 1_000_000 and n % 1_000_000 == 0 else f"{round(n / 1024)}K"


def ts_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def describe(m):
    text = re.sub(r"\s+", " ", (m.get("description") or "").replace("\n", " ")).strip()
    first = re.split(r"(?<=[.!?])\s", text, 1)[0] if text else ""
    first = (first[:217] + "...") if len(first) > 220 else first
    return (first + " " if first else "") + "Routed through OpenRouter."


def caps(m):
    params = set(m.get("supported_parameters") or [])
    arch = m.get("architecture") or {}
    return {
        "tools": "tools" in params,
        "vision": "image" in (arch.get("input_modalities") or []),
        "reasoning": "reasoning" in params,
        "text_out": "text" in (arch.get("output_modalities") or ["text"]),
        "ctx": int(m.get("context_length") or (m.get("top_provider") or {}).get("context_length") or 0),
        "max_out": int((m.get("top_provider") or {}).get("max_completion_tokens") or 0),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", help="read the OpenRouter catalog from this JSON file instead of the API")
    ap.add_argument("--check", action="store_true", help="report drift and exit 1 instead of writing")
    ap.add_argument("--add", action="append", default=[], help="add a paid OpenRouter model id to openrouter-sync.json")
    a = ap.parse_args()

    settings = json.loads(SETTINGS.read_text())
    if a.add:
        settings["paid"] = sorted(set(settings["paid"]) | set(a.add))
        if not a.check:
            SETTINGS.write_text(json.dumps(settings, indent=2) + "\n")
    fee = settings["fee"]

    if a.catalog:
        raw = Path(a.catalog).read_text()
    else:
        req = urllib.request.Request(CATALOG_URL, headers={"User-Agent": "openpaths-sync"})
        raw = urllib.request.urlopen(req, timeout=60).read()
    catalog = {m["id"]: m for m in json.loads(raw)["data"]}

    yaml_text = CONFIG.read_text()
    y_head, y_old, y_tail = split_block(yaml_text, Y_BEGIN, Y_END)
    manual = manual_models(y_head + y_tail)
    taken = {m["id"] for m in manual} | {al for m in manual for al in m["aliases"]}
    by_pmid = {m["pmid"]: m["id"] for m in manual if m["provider"] == "openrouter" and m["pmid"]}

    missing = [p for p in settings["paid"] if p not in catalog]
    if missing:
        sys.exit(f"paid ids not in the OpenRouter catalog: {', '.join(missing)}")

    rank = {p: i for i, p in enumerate(settings["free_rank"])}
    free = []
    for pmid, m in catalog.items():
        c = caps(m)
        if not pmid.endswith(":free") or pmid in settings["free_exclude"]:
            continue
        if not (c["tools"] and c["text_out"]) or c["ctx"] < settings["free_min_context"]:
            continue
        free.append(pmid)
    free.sort(key=lambda p: (rank.get(p, len(rank)), -caps(catalog[p])["ctx"], p))
    if ROUTER in catalog:
        free.append(ROUTER)
    if not free:
        sys.exit("no free tool-capable OpenRouter models found; refusing to empty openpaths/free")

    def gen_id(pmid):
        if pmid == ROUTER:
            return "or/openrouter-free"
        short = "or/" + pmid.split("/", 1)[-1]
        return short if short not in taken else "or/" + pmid

    entries, site, ladder = [], [], []
    for pmid in free + sorted(set(settings["paid"]) - set(free)):
        if pmid in by_pmid:
            if pmid in free:
                ladder.append(by_pmid[pmid])
            continue
        m, c, mid = catalog[pmid], caps(catalog[pmid]), gen_id(pmid)
        is_free = pmid in free
        if is_free:
            ladder.append(mid)
        pr = m.get("pricing") or {}
        extra = {k: v for k, v in pr.items() if k not in ("prompt", "completion", "input_cache_read", "input_cache_write", "overrides") and float(v or 0)}
        if pr.get("overrides") and not is_free:
            print(f"note: {pmid} has tiered/time-of-day overrides; billed at base rate", file=sys.stderr)
        if extra and not is_free:
            print(f"warn: {pmid} has unbilled OpenRouter charges {extra}", file=sys.stderr)
        aliases = [al for al in (pmid, "openrouter/" + pmid) if al not in taken and al != mid]
        if not is_free:
            base = pmid.split("/", 1)[-1]
            if base not in taken:
                aliases.append(base)
        taken.update(aliases + [mid])
        inp = 0 if is_free else per_million(pr.get("prompt"), fee)
        out = 0 if is_free else per_million(pr.get("completion"), fee)
        cache = 0 if is_free else per_million(pr.get("input_cache_read"), fee)
        lines = []
        if not is_free:
            lines.append(f"  # openrouter: in={fmt(raw_per_million(pr.get('prompt')))} out={fmt(raw_per_million(pr.get('completion')))}"
                         f" cache={fmt(raw_per_million(pr.get('input_cache_read')))} per 1M, +{fee * 100:g}% fee")
        lines += [
            f"  - id: {json.dumps(mid)}",
            "    provider: openrouter",
            f"    provider_model_id: {json.dumps(pmid)}",
            f"    input_price_per_1m: {fmt(inp)}",
        ]
        if cache:
            lines.append(f"    input_cache_hit_price_per_1m: {fmt(cache)}")
        lines.append(f"    output_price_per_1m: {fmt(out)}")
        if aliases:
            lines.append(f"    aliases: [{', '.join(json.dumps(x) for x in aliases)}]")
        if c["ctx"]:
            lines.append(f"    context_window: {c['ctx']}")
        if c["max_out"]:
            lines.append(f"    max_output_tokens: {c['max_out']}")
        lines += [
            "    supports_streaming: true",
            f"    supports_tools: {str(c['tools']).lower()}",
            f"    supports_vision: {str(c['vision']).lower()}",
        ]
        entries.append("\n".join(lines))
        tags = (["free"] if is_free else []) + ["general"] + (["vision"] if c["vision"] else []) + \
               (["reasoning"] if c["reasoning"] else []) + (["agentic"] if c["tools"] else [])
        released = datetime.datetime.fromtimestamp(int(m.get("created") or 0), datetime.timezone.utc).strftime("%Y-%m-%d")
        site.append("\n".join([
            "  {",
            f"    id: {ts_str(mid)},",
            f"    name: {ts_str(m.get('name') or pmid)},",
            "    provider: 'OpenRouter',",
            f"    description: {ts_str(describe(m))},",
            f"    contextLength: {ts_str(ctx_label(c['ctx']) if c['ctx'] else 'N/A')},",
            f"    priceInput: {fmt(inp)},",
            f"    priceOutput: {fmt(out)},",
            f"    tags: [{', '.join(ts_str(t) for t in tags)}],",
            *([f"    aliases: [{', '.join(ts_str(x) for x in aliases)}],"] if aliases else []),
            f"    released: {ts_str(released)},",
            "    popularity: 10",
            "  },",
        ]))

    top = catalog[free[0]]
    tc = caps(top)
    free_aliases = [al for al in settings["free_aliases"] if al not in taken]
    if FREE_ID in taken:
        sys.exit(f"{FREE_ID} is configured outside the openrouter-sync block; remove it there first")
    entries.insert(0, "\n".join([
        f"  - id: {json.dumps(FREE_ID)}",
        "    provider: openrouter",
        f"    provider_model_id: {json.dumps(free[0])}",
        "    input_price_per_1m: 0",
        "    output_price_per_1m: 0",
        *([f"    aliases: [{', '.join(json.dumps(x) for x in free_aliases)}]"] if free_aliases else []),
        f"    context_window: {tc['ctx']}",
        *([f"    max_output_tokens: {tc['max_out']}"] if tc["max_out"] else []),
        "    supports_streaming: true",
        "    supports_tools: true",
        f"    supports_vision: {str(tc['vision']).lower()}",
        "    fallback_models:",
        *[f"      - {json.dumps(x)}" for x in ladder[1:]],
    ]))
    site.insert(0, "\n".join([
        "  {",
        f"    id: {ts_str(FREE_ID)},",
        "    name: 'OpenPaths Free',",
        "    provider: 'OpenPaths',",
        f"    description: {ts_str('Zero-cost route across the free OpenRouter models: starts on ' + (top.get('name') or free[0]) + ' and falls through the free ladder, never onto a paid model.')},",
        f"    contextLength: {ts_str(ctx_label(tc['ctx']))},",
        "    priceInput: 0,",
        "    priceOutput: 0,",
        "    tags: ['free', 'general', 'agentic'],",
        *([f"    aliases: [{', '.join(ts_str(x) for x in free_aliases)}],"] if free_aliases else []),
        f"    released: {ts_str(datetime.datetime.fromtimestamp(int(top.get('created') or 0), datetime.timezone.utc).strftime('%Y-%m-%d'))},",
        "    popularity: 40",
        "  },",
    ]))

    y_body = "\n" + "\n\n".join(entries) + "\n"
    if y_old is None:
        if Y_ANCHOR not in yaml_text:
            sys.exit(f"anchor {Y_ANCHOR!r} not found in config.yaml")
        new_yaml = yaml_text.replace(Y_ANCHOR, Y_BEGIN + y_body + Y_END + "\n\n" + Y_ANCHOR, 1)
    else:
        new_yaml = y_head + Y_BEGIN + y_body + Y_END + y_tail

    site_text = SITE.read_text()
    t_head, t_old, t_tail = split_block(site_text, T_BEGIN, T_END)
    t_body = "\n" + "\n".join(site) + "\n"
    if t_old is None:
        if T_ANCHOR not in site_text:
            sys.exit("catalogModels closing anchor not found in src/data/models.ts")
        new_site = site_text.replace(T_ANCHOR, "\n" + T_BEGIN + t_body + T_END + T_ANCHOR, 1)
    else:
        new_site = t_head + T_BEGIN + t_body + T_END + t_tail

    caps_text = CAPS.read_text()
    fm = re.search(r"FREE_MODEL_IDS = \[([^\]]*)\]", caps_text)
    old_gen = set(re.findall(r'  - id: "([^"]+)"', y_old or ""))
    keep = [x for x in re.findall(r"'([^']+)'", fm[1]) if x not in old_gen]
    gen_free = [FREE_ID] + [x for x in ladder if x not in keep and not x in {m["id"] for m in manual}]
    ids = keep + [x for x in gen_free if x not in keep]
    new_caps = caps_text[:fm.start(1)] + ", ".join(ts_str(x) for x in ids) + caps_text[fm.end(1):]

    stale = sorted(p for p, i in by_pmid.items() if p not in catalog)
    for p in stale:
        print(f"warn: {by_pmid[p]} ({p}) is no longer in the OpenRouter catalog", file=sys.stderr)

    changed = [p.relative_to(ROOT) for p, old, new in ((CONFIG, yaml_text, new_yaml), (SITE, site_text, new_site), (CAPS, caps_text, new_caps)) if old != new]
    print(f"openpaths/free: {' -> '.join(ladder)}")
    print(f"paid: {', '.join(settings['paid']) or '-'}")
    if a.check:
        if changed:
            print(f"drift: {', '.join(map(str, changed))}")
            sys.exit(1)
        return
    CONFIG.write_text(new_yaml)
    SITE.write_text(new_site)
    CAPS.write_text(new_caps)
    print(f"wrote: {', '.join(map(str, changed)) or 'nothing'}")


if __name__ == "__main__":
    main()
