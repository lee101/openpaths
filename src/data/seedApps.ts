export function seedAppStats(app: SeedApp): AppUsageStats {
  return {
    ...app,
    app_id: `seed-${app.slug}`,
    total_requests: 0,
    models: [],
  };
}

export function findSeedApp(slug: string) {
  return seedApps.find(app => app.slug === slug);
}
