export function parseContextLength(ctx: string): number {
  if (ctx === 'N/A') return 0;
  const match = ctx.match(/([\d.]+)([KMB]?)/);
  if (!match) return 0;
  const num = parseFloat(match[1]);
  const unit = match[2];
  if (unit === 'M') return num * 1_000_000;
  if (unit === 'K') return num * 1_000;
  return num;
}

